#!/bin/bash
# msvc-object-probe.sh - Pin down what MSVC's C1605 actually runs out of.
# Usage: ./scripts/msvc-object-probe.sh [build-dir]
#
# Context: since v1.7.0 the Windows job dies with
#   fatal error C1605: compiler limit: object file size cannot exceed 4 GB
# on exactly two translation units (src/demo/glass_water/Hud.cpp and
# src/demo/night_forest/Hud.cpp). Two explanations were already falsified by
# CI: "/bigobj raises the 4 GB ceiling, so the section table was exhausted"
# (run 42760865230 shows /bigobj on the cl command line with the byte-identical
# error) and "the TU is simply too big" (night_forest/main.cpp and
# glass_water/main.cpp are larger, import gldx and include the same Hud.h, and
# compile fine). clang has no equivalent limit, so no local build can observe
# any of this; a full Windows build costs ~15 minutes per guess.
#
# So this script turns one CI round into a batch of answers. For each failing TU
# it recovers the original cl command line from ninja and re-runs it as a
# compile-only variant set:
#   baseline       unchanged, must reproduce C1605
#   no-bigobj      if the message becomes C1128 the limit really is section
#                  count and /bigobj is not taking effect on this path
#   /Ob1           fewer inline function bodies -> fewer COMDAT sections
#   /Os            same pressure from the size-directed optimiser instead
#   /Zc:inline-    the opposite direction: keep unreferenced inline bodies in
#                  the object, which should make a section problem worse
#   skeleton TU    the same preamble (Platform.h + import gldx + Hud.h + STL +
#                  glm) with an empty body, which separates "any importer of
#                  this interface hits the wall" from "something in these two
#                  bodies does"
# Each variant compiles in seconds, and the exit code plus the first error line
# is all the evidence needed. The script never fails the build: it is meant to
# run from a step guarded by `if: failure()`.

set -uo pipefail

BUILD_DIR="${1:-build}"
if [ ! -d "$BUILD_DIR" ]; then
    echo "no build directory at $BUILD_DIR" >&2
    exit 0
fi
cd "$BUILD_DIR" || exit 0

Demos="glass_water night_forest"

# compile_variant <label> <cl-prefix> <out-obj> <source>
compile_variant() {
    local label="$1" prefix="$2" obj="$3" src="$4"
    local log="${obj}.log"
    # eval because the prefix is a full cl command line with a @response file.
    eval "$prefix /Fo$obj /FS -c $src" >"$log" 2>&1
    local rc=$?
    local codes
    codes="$(grep -oE '(fatal )?error [A-Z][0-9]+' "$log" | sort -u | head -3 | tr '\n' ' ')"
    printf '  %-16s rc=%-3s %s\n' "$label" "$rc" "$codes"
    if [ "$rc" -eq 0 ]; then
        local sections size
        sections="$(MSYS_NO_PATHCONV=1 dumpbin /headers "$obj" 2>/dev/null |
                    grep -m1 -oE '[0-9]+ sections' || echo '?')"
        size="$(stat -c %s "$obj" 2>/dev/null || stat -f %z "$obj" 2>/dev/null || echo '?')"
        printf '  %-16s -> produced %s bytes, %s\n' "" "$size" "$sections"
    fi
}

for demo in $Demos; do
    echo "================ ${demo}/Hud.cpp ================"
    obj="src/demo/CMakeFiles/d_${demo}.dir/${demo}/Hud.cpp.obj"
    cmd="$(ninja -t commands "$obj" 2>/dev/null | tail -1)"
    if [ -z "$cmd" ]; then
        echo "  no ninja command found for $obj, skipping"
        continue
    fi
    src="${cmd##* -c }"
    echo "  source: $src"
    # Keep everything up to the first /Fo; the object path, the PDB directory
    # and the source are re-attached per variant.
    prefix="${cmd%% /Fo*}"
    nobig="${prefix// \/bigobj/}"

    compile_variant "baseline"      "$prefix"               "probe_${demo}_base.obj"  "$src"
    compile_variant "no-bigobj"     "$nobig"                "probe_${demo}_nobig.obj" "$src"
    compile_variant "/Ob1"          "$prefix /Ob1"          "probe_${demo}_ob1.obj"   "$src"
    compile_variant "/Os"           "$prefix /Os"           "probe_${demo}_os.obj"    "$src"
    compile_variant "/Zc:inline-"   "$prefix /Zc:inline-"   "probe_${demo}_zci.obj"   "$src"

    # Skeleton importer: same header/module preamble, no panel code at all. It
    # has to sit next to the demo so that `#include "Hud.h"` resolves the same
    # way it does for the real TU.
    skel_src="../src/demo/${demo}/msvc_probe_skeleton.cpp"
    cat >"$skel_src" <<'PROBE_EOF'
// Generated by scripts/msvc-object-probe.sh; not part of any target.
#include "gldx/core/Platform.h"

import gldx;

#include "Hud.h"

#include <algorithm>
#include <cstdio>
#include <string>
#include <vector>

#include <glm/glm.hpp>

void msvc_probe_skeleton() {}
PROBE_EOF
    compile_variant "skeleton"      "$prefix"               "probe_${demo}_skel.obj"  "$skel_src"
    rm -f "$skel_src"
done

echo "probe complete"
exit 0
